//! Translations of the user interface, gettext style.
//!
//! The code holds the English texts (`tr!("Copy")`); the other languages
//! are in `po/<lang>.po`, compiled into the binary by `build.rs`. A file
//! `<config>/lang/<lang>.po` adds a language or overrides single messages of
//! a built-in one. A message without a translation is shown in English.
//!
//! Library crates return [`rolid_text::Text`]; [`t`] translates it. The
//! macros `tr!`, `trc!`, `trn!`, `trnc!` take the same arguments as
//! `txt!`, `txtc!`, `txtn!`, `txtnc!` and return the translated `String`.
//!
//! The language is global and can change at run time ([`set_language`]):
//! the UI calls `tr!` in every frame, so it switches at once.

