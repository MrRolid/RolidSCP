/// The languages of the program: code, name in that language.
pub const LANGUAGES: [(&str, &str); 8] = [
    ("en", "English"),
    ("cs", "Čeština"),     // i18n-ok: language name in its own language
    ("de", "Deutsch"),
    ("fr", "Français"),    // i18n-ok: language name in its own language
    ("pl", "Polski"),
    ("es", "Español"),     // i18n-ok: language name in its own language
    ("nb", "Norsk bokmål"), // i18n-ok: language name in its own language
    ("da", "Dansk"),
];

/// The name of a language in that language (a code for one added by the user).
pub fn language_name(code: &str) -> String {
    LANGUAGES.iter().find(|(c, _)| *c == code).map(|(_, n)| n.to_string()).unwrap_or_else(|| code.to_string())
}

/// Plural rules of the built-in languages, used when a .po file has none.
fn default_plural_forms(lang: &str) -> &'static str {
    match lang {
        "cs" | "sk" => "nplurals=3; plural=(n==1) ? 0 : (n>=2 && n<=4) ? 1 : 2;",
        "pl" => "nplurals=3; plural=(n==1 ? 0 : n%10>=2 && n%10<=4 && (n%100<10 || n%100>=20) ? 1 : 2);",
        "fr" => "nplurals=2; plural=(n > 1);",
        _ => "nplurals=2; plural=(n != 1);",
    }
}

/// The language from the environment: the first set of `LC_ALL`,
/// `LC_MESSAGES`, `LANG` ("cs_CZ.UTF-8" → "cs"). `available` are the codes
/// that can be shown; anything else (also "C", "POSIX") means English.
pub fn language_from_env(get: impl Fn(&str) -> Option<String>, available: &[String]) -> String {
    let value = ["LC_ALL", "LC_MESSAGES", "LANG"].iter().filter_map(|k| get(k)).find(|v| !v.trim().is_empty());
    let Some(v) = value else { return "en".into() };
    let base = v.split(['.', '@']).next().unwrap_or("");
    let lang = base.split(['_', '-']).next().unwrap_or("").to_ascii_lowercase();
    let lang = match lang.as_str() {
        // Norwegian without a written standard, and Nynorsk: Bokmål is closest.
        "no" | "nn" => "nb".to_string(),
        _ => lang,
    };
    if available.contains(&lang) {
        lang
    } else {
        "en".into()
    }
}

/// One loaded language.
#[derive(Debug, Clone)]
pub struct Catalog {
    rules: Rules,
    /// msgid → forms (messages without a context).
    plain: HashMap<String, Vec<String>>,
    /// "ctx\u{4}msgid" → forms.
    with_ctx: HashMap<String, Vec<String>>,
}

impl Catalog {
    fn new(lang: &str) -> Self {
        Self { rules: Rules::parse(default_plural_forms(lang)).expect("built-in plural rules"), plain: HashMap::new(), with_ctx: HashMap::new() }
    }

    fn insert(&mut self, ctx: &str, id: &str, forms: Vec<String>) {
        if ctx.is_empty() {
            self.plain.insert(id.to_string(), forms);
        } else {
            self.with_ctx.insert(format!("{ctx}\u{4}{id}"), forms);
        }
    }

    fn get(&self, ctx: Option<&str>, id: &str) -> Option<&Vec<String>> {
        match ctx {
            None | Some("") => self.plain.get(id),
            Some(c) => self.with_ctx.get(&format!("{c}\u{4}{id}")),
        }
    }

    /// Number of translated messages.
    pub fn len(&self) -> usize {
        self.plain.len() + self.with_ctx.len()
    }

    pub fn is_empty(&self) -> bool {
        self.len() == 0
    }

    /// The built-in catalog of `lang` (empty for English or an unknown code).
    pub fn embedded(lang: &str) -> Self {
        let mut c = Self::new(lang);
        if let Some(e) = EMBEDDED.iter().find(|e| e.lang == lang) {
            match Rules::parse(e.plural_forms) {
                Ok(r) => c.rules = r,
                Err(err) => tracing::warn!("built-in {lang}.po: bad Plural-Forms ({err}), using defaults"),
            }
            for (ctx, id, forms) in e.entries {
                c.insert(ctx, id, forms.iter().map(|s| s.to_string()).collect());
            }
        }
        c
    }

    /// Merge a user's .po file over this catalog (its messages win). A file
    /// that cannot be read or parsed changes nothing: the error is returned
    /// for the log.
    pub fn merge_po(&mut self, text: &[u8]) -> Result<usize, String> {
        // polib must not take the program down, whatever the file holds.
        let parsed = std::panic::catch_unwind(|| polib::po_file::parse_from_reader(text))
            .map_err(|_| "the parser failed".to_string())?
            .map_err(|e| e.to_string())?;
        let rules = &parsed.metadata.plural_rules;
        let header = format!("nplurals={}; plural={};", rules.nplurals, rules.expr);
        let mut next = self.clone();
        // polib's default for a missing header is "nplurals=1; plural=0": keep ours then.
        if !(rules.nplurals == 1 && rules.expr.trim() == "0") {
            next.rules = Rules::parse(&header).map_err(|e| format!("Plural-Forms: {e}"))?;
        }
        let mut n = 0;
        for m in parsed.messages() {
            if m.is_fuzzy() || !m.is_translated() || m.msgid().is_empty() {
                continue;
            }
            let forms: Vec<String> = if m.is_plural() {
                m.msgstr_plural().cloned().unwrap_or_default()
            } else {
                m.msgstr().map(|s| vec![s.to_string()]).unwrap_or_default()
            };
            next.insert(m.msgctxt().unwrap_or(""), m.msgid(), forms);
            n += 1;
        }
        *self = next;
        Ok(n)
    }

    /// The translation of a message (template, before the placeholders are
    /// filled), or the English one.
    pub fn template(&self, text: &Text) -> String {
        let forms = self.get(text.ctx, text.id);
        let idx = match text.plural {
            Some((_, n)) => self.rules.index(n),
            None => 0,
        };
        match forms.and_then(|f| f.get(idx)).filter(|s| !s.is_empty()) {
            Some(s) => s.clone(),
            None => text.english_template().to_string(),
        }
    }
}

/// The active language and formats.
#[derive(Debug, Clone)]
pub struct Active {
    pub lang: String,
    pub catalog: Arc<Catalog>,
    pub locale: Locale,
}

static ACTIVE: RwLock<Option<Active>> = RwLock::new(None);

fn active() -> Active {
    ACTIVE.read().ok().and_then(|a| a.clone()).unwrap_or_else(|| Active {
        lang: "en".into(),
        catalog: Arc::new(Catalog::new("en")),
        locale: Locale::EN,
    })
}

/// The code of the active language.
pub fn current_language() -> String {
    active().lang
}

/// The codes that can be chosen: the built-in languages and those with a
/// file in `user_dir`.
pub fn available(user_dir: Option<&Path>) -> Vec<String> {
    let mut v: Vec<String> = LANGUAGES.iter().map(|(c, _)| c.to_string()).collect();
    if let Some(dir) = user_dir {
        if let Ok(rd) = std::fs::read_dir(dir) {
            let mut extra: Vec<String> = rd
                .filter_map(|e| e.ok())
                .filter_map(|e| {
                    let p = e.path();
                    let stem = p.file_stem()?.to_str()?.to_string();
                    (p.extension()? == "po" && !stem.is_empty() && stem.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')).then_some(stem)
                })
                .filter(|s| !v.contains(s))
                .collect();
            extra.sort();
            v.extend(extra);
        }
    }
    v
}

/// What [`set_language`] did.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Applied {
    pub lang: String,
    /// Problems with the user's file (for the log; the built-in text is used).
    pub warnings: Vec<String>,
}

/// Switch the language: `choice` is a code or `None` for the system
/// language (environment); `date_iso` writes dates as 2026-11-08 in every
/// language; `user_dir` holds the user's .po files.
pub fn set_language(choice: Option<&str>, date_iso: bool, user_dir: Option<&Path>) -> Applied {
    let avail = available(user_dir);
    let lang = match choice {
        Some(c) if avail.iter().any(|a| a == c) => c.to_string(),
        _ => language_from_env(|k| std::env::var(k).ok(), &avail),
    };
    let (catalog, warnings) = load(&lang, user_dir);
    let mut locale = Locale::of(&lang);
    if date_iso {
        locale.date = DateStyle::Iso;
    }
    if let Ok(mut a) = ACTIVE.write() {
        *a = Some(Active { lang: lang.clone(), catalog: Arc::new(catalog), locale });
    }
    Applied { lang, warnings }
}

/// The catalog of `lang`: built in, then the user's file over it.
pub fn load(lang: &str, user_dir: Option<&Path>) -> (Catalog, Vec<String>) {
    let mut c = Catalog::embedded(lang);
    let mut warnings = Vec::new();
    if let Some(dir) = user_dir {
        let path = dir.join(format!("{lang}.po"));
        match std::fs::read(&path) {
            Ok(bytes) => match c.merge_po(&bytes) {
                Ok(n) => tracing::info!("translation {}: {n} messages", path.display()),
                Err(e) => {
                    let w = format!("{}: {e}; using the built-in translation", path.display());
                    tracing::warn!("{w}");
                    warnings.push(w);
                }
            },
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => {}
            Err(e) => {
                let w = format!("{}: {e}", path.display());
                tracing::warn!("{w}");
                warnings.push(w);
            }
        }
    }
    (c, warnings)
}

/// Translate a message and fill in its placeholders.
pub fn t(text: &Text) -> String {
    let a = active();
    translate_with(&a, text)
}

fn translate_with(a: &Active, text: &Text) -> String {
    let template = a.catalog.template(text);
    fill(&template, |name| {
        if let Some((_, v)) = text.args.iter().find(|(n, _)| *n == name) {
            return Some(match v {
                Arg::Str(s) => s.clone(),
                Arg::Int(i) => a.locale.int(*i),
                Arg::Text(t) => translate_with(a, t),
            });
        }
        match (name, text.plural) {
            ("n", Some((_, n))) => Some(a.locale.int(n as i128)),
            _ => None,
        }
    })
}

/// Translate a string marked with `n!` in a library.
pub fn t_str(id: &'static str) -> String {
    t(&Text::new(id))
}

/// Translate a string marked with `nc!(ctx, …)`.
pub fn tc_str(ctx: &'static str, id: &'static str) -> String {
    t(&Text { ctx: Some(ctx), ..Text::new(id) })
}

/// A whole number in the active language ("1 234").
pub fn num(v: impl Into<i128>) -> String {
    active().locale.int(v.into())
}

/// A decimal number in the active language ("38,1").
pub fn decimal(v: f64, places: usize) -> String {
    active().locale.decimal(v, places)
}

/// A size in bytes ("38,1 MB"); the unit names are translatable.
pub fn size(bytes: u64) -> String {
    let units = [
        crate::trc!("unit", "B"),
        crate::trc!("unit", "kB"),
        crate::trc!("unit", "MB"),
        crate::trc!("unit", "GB"),
        crate::trc!("unit", "TB"),
        crate::trc!("unit", "PB"),
    ];
    active().locale.size(bytes, &units)
}

/// Date and time in the active format.
pub fn datetime(t: std::time::SystemTime, seconds: bool) -> String {
    active().locale.datetime(t, seconds)
}

/// The active number and date conventions.
pub fn locale() -> Locale {
    active().locale
}

/// Translated text: `tr!("Copy {n} files", n = count)`.
#[macro_export]
macro_rules! tr {
    ($($t:tt)*) => { $crate::t(&$crate::rolid_text::txt!($($t)*)) };
}

/// Translated text with a context: `trc!("verb", "Open")`.
#[macro_export]
macro_rules! trc {
    ($($t:tt)*) => { $crate::t(&$crate::rolid_text::txtc!($($t)*)) };
}

